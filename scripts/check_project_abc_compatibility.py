#!/usr/bin/env python3
"""Explicit one-off configuration-refactor audit, not a permanent desired-state freeze."""
import argparse
import json
import subprocess
import yaml
from build_landing_zone_config import ROOT, assemble


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", required=True, help="Reviewed pre-refactor Git commit")
    args = parser.parse_args()
    base = subprocess.check_output(["git", "rev-parse", "--verify", "--end-of-options", args.base + "^{commit}"], cwd=ROOT, text=True).strip()
    def original(path):
        return subprocess.check_output(["git", "show", base + ":" + path], cwd=ROOT)
    raw = yaml.safe_load(original("BTP/landing-zone.yaml"))
    actual = assemble(ROOT / "BTP/config")
    if json.dumps(raw, sort_keys=True) != json.dumps(actual, sort_keys=True):
        raise SystemExit("Project ABC configuration changed (values omitted)")
    if original("BTP/landing-zone.yaml") != (ROOT / "BTP/landing-zone.yaml").read_bytes():
        raise SystemExit("Project ABC generated artifact changed")
    roots = ["BTP", "CloudFoundry", "CloudFoundry/environments"]
    for root in roots:
        names = subprocess.check_output(["git", "ls-tree", "--name-only", base, root + "/"], cwd=ROOT, text=True).splitlines()
        for name in names:
            if name.endswith((".tf", ".lock.hcl")) and original(name) != (ROOT / name).read_bytes():
                raise SystemExit("Existing deployment root or provider lock changed: " + name)
    print("Project ABC: all values/types/omissions, generated bytes, existing root files and provider locks unchanged against " + base)


if __name__ == "__main__":
    main()
